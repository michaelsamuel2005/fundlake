"""Generate docs/DATA_DICTIONARY.md from the built database catalog, dbt model descriptions and docs/columns.yaml."""
import sys
from pathlib import Path

import duckdb
import yaml

ROOT = Path(__file__).resolve().parents[1]


def build(db: Path) -> str:
    cols = yaml.safe_load((ROOT / "docs/columns.yaml").read_text())
    schema = yaml.safe_load((ROOT / "dbt/models/schema.yml").read_text())
    desc = {m["name"]: m.get("description", "") for m in schema["models"]}
    con = duckdb.connect(str(db), read_only=True)
    out = ["# Data dictionary", "", "Generated by `scripts/gen_dictionary.py` from the built database. All data is synthetic.", ""]
    for sch in ("silver", "gold"):
        out += [f"## {sch.title()} layer", ""]
        for (t,) in con.execute("select table_name from information_schema.tables where table_schema=? order by 1", [sch]).fetchall():
            n = con.execute(f"select count(*) from {sch}.{t}").fetchone()[0]
            out += [f"### {sch}.{t}", "", (desc.get(t) or "").strip() or "_See model SQL._", "", f"Rows in the reference build: {n:,}.", "",
                    "| Column | Type | Definition |", "|---|---|---|"]
            for c, ty in con.execute("select column_name, data_type from information_schema.columns where table_schema=? and table_name=? order by ordinal_position", [sch, t]).fetchall():
                out.append(f"| {c} | {ty.lower()} | {cols.get(c, 'MISSING')} |")
            out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    db = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "data/fundlake.duckdb"
    (ROOT / "docs/DATA_DICTIONARY.md").write_text(build(db))
    print("written docs/DATA_DICTIONARY.md")
